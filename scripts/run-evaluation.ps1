$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
Push-Location -LiteralPath $repoRoot
try {
    Get-Command java -ErrorAction Stop | Out-Null
    Get-Command mvn -ErrorAction Stop | Out-Null
    Get-Command docker -ErrorAction Stop | Out-Null
    $startedAt = [DateTime]::UtcNow
    & mvn -B '-Dtest=GoldenEvalIntegrationTest' test
    $testExit = $LASTEXITCODE
    if ((Test-Path -LiteralPath 'target/eval-report.md') -and (Get-Item -LiteralPath 'target/eval-report.md').LastWriteTimeUtc -ge $startedAt) {
        Get-Content -LiteralPath 'target/eval-report.md' -Raw | Write-Output
    }
    else { Write-Output 'No fresh evaluation report was generated by this invocation.' }
    if ($testExit -ne 0) { throw "Golden evaluation failed (Maven exit $testExit). Inspect target/surefire-reports and any generated eval report." }
    Write-Output 'Reports: target/eval-report.json and target/eval-report.md'
}
finally { Pop-Location }
